CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    VARCHAR(100) NOT NULL,
    last_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    phone         VARCHAR(20),
    role          SMALLINT NOT NULL DEFAULT 2,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT users_first_name_not_blank CHECK (LENGTH(TRIM(first_name)) > 0),
    CONSTRAINT users_last_name_not_blank CHECK (LENGTH(TRIM(last_name)) > 0),
    CONSTRAINT users_email_lowercase CHECK (email = LOWER(email)),
    CONSTRAINT users_role_valid CHECK (role IN (1, 2))
);

CREATE TABLE events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200) NOT NULL,
    description     TEXT NOT NULL DEFAULT '',
    location        VARCHAR(255) NOT NULL DEFAULT '',
    starts_at       TIMESTAMPTZ NOT NULL,
    total_seats     INTEGER NOT NULL,
    available_seats INTEGER NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT events_title_not_blank CHECK (LENGTH(TRIM(title)) > 0),
    CONSTRAINT events_total_seats_positive CHECK (total_seats > 0),
    CONSTRAINT events_seats_valid CHECK (available_seats >= 0 AND available_seats <= total_seats)
);

CREATE TABLE bookings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id),
    event_id     BIGINT NOT NULL REFERENCES events(id),
    quantity     SMALLINT NOT NULL,
    status       SMALLINT NOT NULL DEFAULT 1,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    cancelled_at TIMESTAMPTZ,
    CONSTRAINT bookings_one_per_user_event UNIQUE (user_id, event_id),
    CONSTRAINT bookings_quantity_valid CHECK (quantity BETWEEN 1 AND 4),
    CONSTRAINT bookings_status_valid CHECK (status IN (1, 2)),
    CONSTRAINT bookings_cancellation_valid CHECK (
        (status = 1 AND cancelled_at IS NULL) OR
        (status = 2 AND cancelled_at IS NOT NULL)
    )
);

